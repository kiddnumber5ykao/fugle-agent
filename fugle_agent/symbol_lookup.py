# 預建快查 index:把每個 alias 都 lowercase + 去空白後當 key
def _norm(s: str) -> str:
    return re.sub(r"\s+", "", s.lower())


_ALIAS_INDEX: dict[str, tuple[str, str]] = {}  # alias_normalized → (symbol, official_name)
for sym, name, aliases in _POPULAR:
    for a in aliases:
        _ALIAS_INDEX[_norm(a)] = (sym, name)
    _ALIAS_INDEX[_norm(sym)] = (sym, name)  # 直接打代號也算命中


def _exact_or_contained(query: str) -> list[dict]:
    """精準或子字串對到內建表,回傳所有命中項(去重保序)。"""
    q = _norm(query)
    if not q:
        return []
    out: list[dict] = []
    seen: set[str] = set()

    # 1) 精準命中
    if q in _ALIAS_INDEX:
        sym, name = _ALIAS_INDEX[q]
        out.append({"symbol": sym, "name": name, "source": "builtin", "match": "exact"})
        seen.add(sym)

    # 2) 子字串雙向(query 在 alias 內 或 alias 在 query 內)
    for alias_n, (sym, name) in _ALIAS_INDEX.items():
        if sym in seen:
            continue
        if q in alias_n or alias_n in q:
            out.append({"symbol": sym, "name": name, "source": "builtin",
                        "match": "contains"})
            seen.add(sym)
    return out


def _fugle_search(query: str, fugle_client) -> list[dict]:
    """模糊搜尋 Fugle 全市場 tickers — 慢但完整。"""
    if fugle_client is None:
        return []
    try:
        records = fugle_client.tickers()  # 統一介面,見 client.py
    except Exception:
        return []
    q = _norm(query)
    out: list[dict] = []
    for r in records:
        sym = str(r.get("symbol") or r.get("code") or "").strip()
        # 優先中文名(nameZhTw),Fugle 的 name 欄常是英文
        name = str(r.get("nameZhTw") or r.get("name") or "").strip()
        if not sym or not name:
            continue
        if q in _norm(name) or q in _norm(sym):
            out.append({"symbol": sym, "name": name, "source": "fugle",
                        "match": "contains"})
            if len(out) >= 10:
                break
    return out


def search(query: str, *, fugle_client=None, limit: int = 5) -> list[dict]:
    """主入口:給名字、代號片段、英文名,回傳最多 ``limit`` 筆可能匹配。

    順序:內建熱門表優先(快),不夠才打 Fugle。
    """
    if not query:
        return []
    hits = _exact_or_contained(query)

    if len(hits) < limit:
        seen = {h["symbol"] for h in hits}
        for extra in _fugle_search(query, fugle_client):
            if extra["symbol"] in seen:
                continue
            hits.append(extra)
            seen.add(extra["symbol"])
            if len(hits) >= limit:
                break

    return hits[:limit]
